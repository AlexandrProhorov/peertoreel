/**
 * Multi-scene director: one film, three to five scenes, scene-level retries.
 *
 * The arc is generated once and frozen; scenes are generated against it
 * independently, so a scene that fails twice does not rewrite the film. Every
 * scene goes through the same gates as the single-scene path: schema, repair,
 * visible change.
 */

const SCENE_ATTEMPTS = 4;

function optionValue(name: string): string | undefined {
  const inline = process.argv.find((argument) => argument.startsWith(`${name}=`));

  if (inline !== undefined) {
    return inline.slice(name.length + 1);
  }

  const index = process.argv.indexOf(name);

  if (index < 0) {
    return undefined;
  }

  const value = process.argv[index + 1];

  if (value === undefined || value.startsWith('--')) {
    throw new Error(`Option ${name} requires a value`);
  }

  return value;
}

function stripFence(raw: string): string {
  const trimmed = raw.trim();
  const fenced = /^```(?:json)?\s*([\s\S]*?)\s*```$/.exec(trimmed);

  return fenced?.[1] ?? trimmed;
}

function issuesOf(error: unknown): string[] {
  if (error instanceof z.ZodError) {
    return error.issues.map(
      (issue) => `${issue.path.join('.') || '$'}: ${issue.message}`,
    );
  }

  return [error instanceof Error ? error.message : String(error)];
}

function wrapScene(scene: UiScene, themeId: string): UiEpisode {
  return {
    schemaVersion: 1,
    themeId: scene.themeId ?? themeId,
    captions: false,
    speech: [],
    scenes: [scene],
  } as UiEpisode;
}

/** Only the spec device reaches this path; the union is for the other devices. */
function asSpecScene(scene: UiScene | undefined): SpecScene | null {
  return scene !== undefined && scene.device === 'spec' ? scene : null;
}

async function generateScene(options: {
  topic: string;
  arc: Arc;
  index: number;
  client: ReturnType<typeof createDeepSeekJsonClient>;
  dir: string;
  tokens: { prompt: number; completion: number };
  /** Signatures the film already uses: a tie prefers a composition it lacks. */
  used: ReadonlySet<string>;
}): Promise<{
  scene: UiScene | null;
  attempts: number;
  errors: string[];
  degraded: boolean;
  /** True when the scene was assembled by us, not generated by the model. */
  fallback: boolean;
  reasons: string[];
}> {
  const planned = options.arc.scenes[options.index];

  if (planned === undefined) {
    return {
      scene: null,
      attempts: 0,
      errors: ['arc has no such scene'],
      degraded: false,
      fallback: false,
      reasons: [],
    };
  }

  const errors: string[] = [];
  /* The ladder keeps the best picture, not the last one: content is already
     guaranteed, violations decide, then the film's unused compositions. */
  let best: AttemptCandidate | null = null;
  /* Signature of the previous attempt: the same picture twice is a reason to
     ask for a different composition, not to repeat the prompt. */
  let previousSignature: string | null = null;
  /* The model's own words from rejected attempts: a fallback keeps its sentence
     even when the composition never assembles. */
  const parsedAttempts: unknown[] = [];

  for (let attempt = 1; attempt <= SCENE_ATTEMPTS; attempt += 1) {
    const correction =
      errors.length === 0
        ? ''
        : `\n\nПредыдущая попытка отклонена. Исправь ровно это:\n${errors
            .map((line) => `- ${line}`)
            .join('\n')}`;
    const response = await options.client.complete({
      system: DIRECTOR_SYSTEM_PROMPT,
      user: `${buildUserPrompt(options.topic, {
        seconds: planned.seconds,
        themeId: planned.theme,
        context: sceneContext(options.arc, planned, options.index),
        voiceLines: splitNarrationLines(planned.narration).map(
          (line) => line.text,
        ),
      })}${correction}`,
      temperature: 0.7,
    });

    options.tokens.prompt += response.usage.promptTokens;
    options.tokens.completion += response.usage.completionTokens;

    const raw = stripFence(response.content);

    await writeFile(
      path.join(options.dir, `scene-${options.index + 1}-attempt-${attempt}.json`),
      `${raw}\n`,
      'utf8',
    );

    let parsed: unknown;

    try {
      parsed = parseJsonResponse(raw);
    } catch (error: unknown) {
      errors.splice(0, errors.length, ...issuesOf(error));
      continue;
    }

    parsedAttempts.push(parsed);

    const repairs: Repair[] = [];
    const episode = uiEpisodeSchema.safeParse(normalizeRawEpisode(parsed, repairs));

    for (const repair of repairs) {
      console.log(`salvaged ${repair.path}: ${repair.reason} (${repair.from} -> ${repair.to})`);
    }

    if (!episode.success) {
      errors.splice(0, errors.length, ...issuesWithHints(issuesOf(episode.error)));
      continue;
    }

    const first = episode.data.scenes[0];

    if (first === undefined) {
      errors.splice(0, errors.length, 'scene is missing');
      continue;
    }

    const lineTexts = splitNarrationLines(planned.narration).map(
      (line) => line.text,
    );

    /* Mark the thesis before the frame gate: only that text is protected from
       crossing primitives, service labels stay free. */
    if (first.device === 'spec') {
      const matches = matchSceneLines(first, lineTexts);

      if (matches.problem === null) {
        first.thesisIds = matches.matches.map((match) => match.elementId);
      }
    }

    let repaired: Awaited<ReturnType<typeof repairEpisode>>;

    try {
      repaired = await repairEpisode(wrapScene(first, planned.theme), {
        outDir: path.join(options.dir, `fit-${options.index + 1}`),
      });
    } catch (error: unknown) {
      /* A repair that breaks the contract is a failed attempt, not a crashed
         run: the whole film must survive one bad scene. */
      errors.splice(0, errors.length, ...issuesOf(error));
      continue;
    }

    const fitted = uiEpisodeSchema.safeParse(repaired.episode);

    if (!fitted.success) {
      errors.splice(0, errors.length, ...issuesWithHints(issuesOf(fitted.error)));
      continue;
    }

    const candidate = asSpecScene(fitted.data.scenes[0]);

    if (candidate === null || !hasContent(candidate)) {
      errors.splice(
        0,
        errors.length,
        'сцена без содержания: после ремонта не осталось ни текста, ни объекта — оставь хотя бы один смысловой элемент с текстом',
      );
      continue;
    }

    /* The film reads itself: every spoken line must own a thesis on screen,
       in order. A title invented next to the line would duplicate it. */
    const lineMismatch = sceneLineMismatch(candidate, lineTexts);

    if (lineMismatch !== null) {
      errors.splice(
        0,
        errors.length,
        `экранный текст сцены: ${lineMismatch}. Положи каждую строку реплики целиком в свой текстовый элемент, в том же порядке, и не добавляй других слов`,
      );
      continue;
    }

    const violations: string[] = [];
    const hints: string[] = [];
    /* Frame checks that were calibrated and promoted: a scene that renders with
       text over text is retried with the measurement's own words. Rules still in
       calibration stay out of the gate. */
    const blockingFrame = repaired.violations.filter(
      (violation) =>
        violation.startsWith('critical-overlap:') ||
        violation.startsWith('text-crossed:'),
    );

    if (blockingFrame.length > 0) {
      violations.push(...blockingFrame.map((violation) => `кадр: ${violation}`));
      hints.push(
        ...blockingFrame.map(
          (violation) => `${violation}: разведи элементы или сократи текст, чтобы кадр читался`,
        ),
      );
    }

    if (repaired.overflowing.length > 0) {
      violations.push(`переполнение: ${repaired.overflowing.join(', ')}`);
      hints.push(
        `текст не влезает даже на минимальном кегле (${repaired.overflowing.join(', ')}): сократи текст или увеличь бокс`,
      );
    } else if (blockingFrame.length === 0) {
      let motion: Awaited<ReturnType<typeof checkVisibleChange>>;

      try {
        motion = await checkVisibleChange(
          fitted.data,
          path.join(options.dir, `motion-${options.index + 1}`),
        );
      } catch (error: unknown) {
        /* A frame that cannot be measured is a failed attempt too. */
        errors.splice(0, errors.length, ...issuesOf(error));
        continue;
      }

      if (!motion.changed) {
        violations.push('сцена статична');
        hints.push(
          `сцена статична: кадры ${motion.earlyFrame} и ${motion.lateFrame} совпадают — добавь действие из контракта (type, fill, draw, break, drag, disappear); входы элементов действием не считаются`,
        );
      }
    }

    if (violations.length === 0) {
      return {
        scene: candidate,
        attempts: attempt,
        errors: [],
        degraded: false,
        fallback: false,
        reasons: [],
      };
    }

    const record: AttemptCandidate = {
      scene: candidate,
      violations,
      signature: sceneSignature(candidate).key,
      attempt,
    };

    if (record.signature === previousSignature) {
      hints.push(REPEATED_COMPOSITION);
    }

    previousSignature = record.signature;

    if (preferAttempt(record, best, options.used)) {
      best = record;
    }

    errors.splice(0, errors.length, ...hints);
  }

  if (best !== null) {
    return {
      scene: degradeScene(best.scene, planned.seconds, best.violations),
      attempts: SCENE_ATTEMPTS,
      errors,
      degraded: true,
      fallback: false,
      reasons: [...best.violations],
    };
  }

  /* Every attempt failed before a usable composition existed. The scene keeps
     its place on the timeline: the model's best sentence on our own stage,
     visibly marked as ours. */
  const plannedScene = { id: planned.id, seconds: planned.seconds, theme: planned.theme, intent: planned.intent };
  /* A fallback still has to read: its label is the opening thesis of the line,
     so the voice step can place it on the words it belongs to. */
  const fallbackLine = splitNarrationLines(planned.narration)[0]?.text;
  const fallbackThesis =
    fallbackLine === undefined
      ? null
      : fallbackLine.split(/\s+/u).slice(0, 5).join(' ');
  const title = fallbackThesis ?? titleFromAttempts(parsedAttempts);
  const reason = fallbackThesis !== null
    ? 'fallback: композиция не собралась, тезис из реплики'
    : title === null
      ? 'fallback: композиция не собралась'
      : 'fallback: композиция не собралась, заголовок из попытки модели';
  const fallback = uiEpisodeSchema.safeParse(
    normalizeRawEpisode(
      wrapScene(fallbackScene(plannedScene, { title, reasons: [reason] }), planned.theme),
    ),
  );
  const fallbackFirst = fallback.success ? asSpecScene(fallback.data.scenes[0]) : null;

  if (fallbackFirst === null) {
    return {
      scene: null,
      attempts: SCENE_ATTEMPTS,
      errors,
      degraded: false,
      fallback: false,
      reasons: [],
    };
  }

  return {
    scene: fallbackFirst,
    attempts: SCENE_ATTEMPTS,
    errors,
    degraded: true,
    fallback: true,
    reasons: [reason],
  };
}

async function main(): Promise<void> {
  loadEnv({
    path: fileURLToPath(new URL('../../../../../.env', import.meta.url)),
    quiet: true,
  });

  const config = parseDeepSeekSvgEnv(process.env);
  const input = optionValue('--input');

  if (input === undefined) {
    throw new Error('--input <topics.json> is required');
  }

  const cwd = process.cwd();
  const outRoot = path.resolve(cwd, optionValue('--out') ?? 'out/film');
  const withAction = !process.argv.includes('--no-action');
  const targetRaw = optionValue('--seconds');
  const targetSeconds = targetRaw === undefined ? null : Number(targetRaw);
  const topics = topicsSchema.parse(
    JSON.parse(stripBom(await readFile(path.resolve(cwd, input), 'utf8'))),
  );
  const client = createDeepSeekJsonClient({
    apiKey: config.apiKey,
    ...(config.model === undefined ? {} : { model: config.model }),
    maxTokens: 8000,
  });
  const rates = {
    input: config.rates.inputUsdPerMtok,
    output: config.rates.outputUsdPerMtok,
  };
  const report: unknown[] = [];

  for (const entry of topics) {
    const assignment = assignmentFor(entry.slug);
    const dir = path.join(outRoot, entry.slug);
    const tokens = { prompt: 0, completion: 0 };

    await mkdir(dir, { recursive: true });

    let arc: Arc | null = null;
    const arcErrors: string[] = [];
    const arcParser = targetSeconds === null ? arcSchema : arcSchemaFor(arcPlanFor(targetSeconds).seconds);

    for (let attempt = 1; attempt <= 3 && arc === null; attempt += 1) {
      const response = await client.complete({
        system: ARC_SYSTEM_PROMPT,
        user:
          buildArcPrompt(entry.topic, {
            action: withAction,
            form: assignment.form,
            carrier: assignment.carrier,
            ...(targetSeconds === null ? {} : { seconds: targetSeconds }),
          }) +
          (arcErrors.length === 0
            ? ''
            : `\n\nОтклонено валидатором:\n${arcErrors.map((line) => `- ${line}`).join('\n')}`),
        temperature: 0.7,
      });

      tokens.prompt += response.usage.promptTokens;
      tokens.completion += response.usage.completionTokens;

      const raw = stripFence(response.content);

      await writeFile(path.join(dir, `arc-attempt-${attempt}.json`), `${raw}\n`, 'utf8');

      try {
        arc = arcParser.parse(parseJsonResponse(raw));
      } catch (error: unknown) {
        arcErrors.splice(0, arcErrors.length, ...issuesOf(error));
      }
    }

    if (arc === null) {
      console.log(`${entry.slug}: arc FAILED`);
      for (const message of arcErrors) {
        console.log(`  ${message}`);
      }
      report.push({ slug: entry.slug, status: 'arc-failed', errors: arcErrors });
      continue;
    }

    await writeFile(
      path.join(dir, 'arc.json'),
      `${JSON.stringify(arc, null, 2)}\n`,
      'utf8',
    );

    const scenes: UiScene[] = [];
    const sceneReport: unknown[] = [];
    const usedSignatures = new Set<string>();
    let degradedCount = 0;
    let fallbackCount = 0;

    for (let index = 0; index < arc.scenes.length; index += 1) {
      const result = await generateScene({
        topic: entry.topic,
        arc,
        index,
        client,
        dir,
        tokens,
        used: usedSignatures,
      });

      if (result.scene === null) {
        sceneReport.push({
          index: index + 1,
          status: 'missing',
          attempts: result.attempts,
          errors: result.errors,
        });
        continue;
      }

      if (result.degraded) {
        degradedCount += 1;
      }

      if (result.fallback) {
        fallbackCount += 1;
      }

      const plannedScene = arc.scenes[index];

      scenes.push({
        ...result.scene,
        ...(plannedScene === undefined ? {} : { narration: plannedScene.narration }),
      });
      usedSignatures.add(sceneSignature(result.scene).key);
      sceneReport.push({
        index: index + 1,
        /* A fallback is degraded too: it is marked and counted in both, and the
           subset tells how many frames we wrote ourselves. */
        status: result.fallback ? 'fallback' : result.degraded ? 'degraded' : 'ok',
        attempts: result.attempts,
        ...(result.degraded ? { reasons: result.reasons } : {}),
      });
    }

    const usd = (tokens.prompt * rates.input + tokens.completion * rates.output) / 1_000_000;
    const totalSeconds = scenes.reduce((sum, scene) => sum + scene.durationSec, 0);    /* Fade is the default entrance; a whole film of fades stops reading as
       separate beats. The quota is applied here because a scene prompt cannot
       see its neighbours' choices. */
    const variety = enforceEntranceVariety(scenes);
    /* Overlaps shorten the picture: scenes share frames during a transition, so
       the film on screen is shorter than the sum of its scenes. */
    const filmSeconds = placeScenes(variety.scenes, SCENE_FPS).totalFrames / SCENE_FPS;

    /* A film is never written short. The arc's scenes are a promise to the
       voiceover and the subtitles: a missing scene is a hole in speech, so an
       incomplete run stops here instead of producing a shorter video. */
    if (scenes.length !== arc.scenes.length) {
      report.push({
        slug: entry.slug,
        status: 'incomplete',
        thesis: arc.thesis,
        planned: arc.scenes.length,
        produced: scenes.length,
        scenes: sceneReport,
        usd: Number(usd.toFixed(4)),
      });
      console.error(
        `${entry.slug}: INCOMPLETE — ${scenes.length} of ${arc.scenes.length} scenes; episode not written`,
      );
      process.exitCode = 1;
      continue;
    }

    await writeFile(
      path.join(dir, 'episode.json'),
      `${JSON.stringify(
        {
          schemaVersion: 1,
          themeId: arc.scenes[0]?.theme ?? 'studio-dark',
          captions: false,
          speech: [],
          scenes: variety.scenes,
        },
        null,
        2,
      )}\n`,
      'utf8',
    );

    report.push({
      slug: entry.slug,
      status: fallbackCount > 0
        ? 'fallback'
        : degradedCount === 0
          ? 'complete'
          : 'degraded',
      thesis: arc.thesis,
      planned: arc.scenes.length,
      produced: scenes.length,
      degraded: degradedCount,
      fallback: fallbackCount,
      entrancesAdjusted: variety.changed.map((index) => index + 1),
      seconds: Number(totalSeconds.toFixed(1)),
      filmSeconds: Number(filmSeconds.toFixed(1)),
      scenes: sceneReport,
      usd: Number(usd.toFixed(4)),
    });

    console.log(
      `${entry.slug}: ${scenes.length}/${arc.scenes.length} scenes, ${totalSeconds.toFixed(1)}s (film ${filmSeconds.toFixed(1)}s), $${usd.toFixed(4)}${
        degradedCount === 0 ? '' : `, ${degradedCount} degraded`
      }${
        variety.changed.length === 0
          ? ''
          : `, entrances ${variety.changed.map((index) => index + 1).join(',')}`
      }`,
    );

    for (const item of sceneReport as Array<Record<string, unknown>>) {
      if (item['status'] !== 'ok') {
        console.log(
          `  scene ${item['index']}: ${String(item['status']).toUpperCase()} — ${JSON.stringify(
            item['reasons'] ?? item['errors'] ?? null,
          )}`,
        );
      }
    }
  }

  await writeFile(
    path.join(outRoot, 'report.json'),
    `${JSON.stringify(report, null, 2)}\n`,
    'utf8',
  );
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
