/**
 * One spoken line placed on screen by the voice step. Times are scene-local
 * and come from the audio assembly, not from an estimate.
 */
export const narrationLineSchema = z
  .object({
    text: z.string().min(1).max(80),
    startSec: z.number().finite().min(0).max(30),
    endSec: z.number().finite().min(0).max(30),
  })
  .refine((line) => line.endSec >= line.startSec, {
    message: 'a narration line must end after it starts',
    path: ['endSec'],
  });

const sceneBaseShape = {
  id: z.string().min(1).max(64),
  /** How this scene arrives: a cut by default, a slide, a fade, a zoom or a wipe. */
  enter: z.enum(ENTER_IDS).optional(),
  /** Clip-local duration; the composition sums the rounded frame counts. */
  durationSec: z.number().finite().min(0.5).max(20),
  /** Overrides the episode theme for one scene (background switches carry rhythm). */
  themeId: z.enum(UI_THEME_IDS).optional(),
  /**
   * Visual reveal window in seconds: how long the device takes to reveal its
   * content. This is not speech time (see `speech` in the episode).
   */
  revealSec: z.number().finite().min(0.2).max(6).default(1.8),
  /**
   * What the voiceover says over this scene. Spoken copy lives with the scene so
   * the voice step and the subtitles read one source, not a second plan.
   */
  narration: z.string().min(1).max(400).optional(),
  /**
   * The spoken lines with their measured times. The frame shows them in the
   * lower band, one at a time, exactly when the voice says them.
   */
  narrationLines: z.array(narrationLineSchema).max(8).optional(),
  /** Elements whose text is the spoken thesis: nothing may cross them. */
  thesisIds: z.array(z.string().min(1).max(24)).max(8).optional(),
  /**
   * Set when the scene was kept after its attempts ran out: the film never
   * loses a scene, so the frame carries a visible mark and the reasons travel
   * with the episode instead of disappearing into a log.
   */
  degraded: z
    .object({
      reasons: z.array(z.string().min(1).max(200)).min(1).max(8),
    })
    .optional(),
  /**
   * The scene was assembled by the renderer from the plan, not generated by the
   * model: the frame carries a visible mark and the report keeps the reason, so
   * a fallback can never be mistaken for a model scene.
   */
  fallback: z
    .object({
      reason: z.string().min(1).max(200),
    })
    .optional(),
};

export const promptCardSceneSchema = z.object({
  ...sceneBaseShape,
  device: z.literal('prompt-card'),
  badge: z.object({
    label: z.string().min(1).max(24),
    mark: z.enum(['star', 'knot']),
  }),
  cardText: z.string().min(1).max(400),
  caption: z.string().min(1).max(40).nullable(),
});

export const textSelectionSceneSchema = z
  .object({
    ...sceneBaseShape,
    device: z.literal('text-selection'),
    title: z.string().min(1).max(60),
    lines: z.array(z.string().min(1).max(80)).min(2).max(8),
    selectionLineIndex: z.number().int().nonnegative(),
  })
  .superRefine((scene, context) => {
    if (scene.selectionLineIndex >= scene.lines.length) {
      context.addIssue({
        code: 'custom',
        path: ['selectionLineIndex'],
        message: `selectionLineIndex ${scene.selectionLineIndex} is outside ${scene.lines.length} line(s)`,
      });
    }
  });

