/**
 * The spec renderer: a composition the model invented, expressed in contracted
 * primitives. It is validated on the way in, so an unknown primitive, parameter
 * or operation never reaches the renderer.
 */
export const specSceneSchema = z
  .object({
    ...sceneBaseShape,
    device: z.literal('spec'),
    spec: compositionSpecSchema,
  })
  .superRefine((scene, context) => {
    for (const issue of parseComposition(scene.spec).issues) {
      context.addIssue({
        code: 'custom',
        path: ['spec'],
        message: `${issue.code}: ${issue.message}`,
      });
    }

    /* Bounds are not enough: type hierarchy, a visible surface, an accent and
       contrast are part of the gate before a composition may be rendered. */
    for (const issue of lintQuality(scene.spec, scene.themeId ?? 'studio-dark')) {
      context.addIssue({
        code: 'custom',
        path: ['spec'],
        message: `quality/${issue.code}: ${issue.message}`,
      });
    }
  });

