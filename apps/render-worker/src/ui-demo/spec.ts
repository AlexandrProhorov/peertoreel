/**
 * Pilot contract for interface storytelling scenes. It stays local to the
 * renderer: production `peertoreel.storyboard.v1` is untouched until a separate
 * decision wires the pilot into the pipeline.
 */
export const UI_EPISODE_COMPOSITION_ID = 'UiEpisode';
export const UI_LINT_COMPOSITION_ID = 'UiLint';
export const UI_MOTION_COMPOSITION_ID = 'UiMotion';

/**
 * An asset reference carries the content hash of the exact bytes it expects.
 * A changed file fails validation instead of altering a rendered video silently.
 */
export const assetRefSchema = z
  .object({
    key: z.enum(ASSET_KEYS),
    contentHash: z
      .string()
      .length(64)
      .regex(/^[0-9a-f]+$/, 'contentHash must be lowercase sha256'),
  })
  .superRefine((ref, context) => {
    try {
      resolveAsset(ref);
    } catch (error) {
      context.addIssue({
        code: 'custom',
        path: ['key'],
        message: error instanceof Error ? error.message : String(error),
      });
    }
  });

export type AssetRef = z.infer<typeof assetRefSchema>;

