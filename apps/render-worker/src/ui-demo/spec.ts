/** A scene is always at least one frame, same rule as `sceneDurationInFrames`. */
export function uiSceneFrames(scene: UiScene, fps: number): number {
  return Math.max(1, Math.round(scene.durationSec * fps));
}

export function uiEpisodeFrames(episode: UiEpisode, fps: number): number {
  return placeScenes(episode.scenes, fps).totalFrames;
}

export function sceneThemeId(episode: UiEpisode, scene: UiScene) {
  return scene.themeId ?? episode.themeId;
}
