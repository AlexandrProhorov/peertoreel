import type { AssetRepository } from './repository.js';
import { assetPaletteFor } from './style.js';

export interface TieredAssetResolverOptions {
  readonly repository: AssetRepository;
  /** Tier 0 records (`buildStarterAssets` output). */
  readonly starter?: readonly AssetRecord[];
  /** The only provider in M3.6a is the fake; production adapters are M3.6b. */
  readonly provider?: ImageProvider | null;
  /** Defaults to the contract key format; injectable for adapters/tests. */
  readonly objectKeyFor?: (contentHash: string, extension: string) => string;
}

const DEFAULT_DIAGNOSTIC_MESSAGE: Readonly<Record<AssetDiagnostic['code'], string>> = {
  starter_hit: 'Resolved from the curated Tier 0 starter pack',
  cache_hit: 'Resolved from the library cache',
  tag_match: 'Resolved by tag match',
  provider_generated: 'Generated by the image provider',
  provider_skipped: 'Provider skipped: allowProvider is false or no enabled provider is configured',
  provider_failed:
    'Provider failed after its retries; the resolver continued to the fallback tier',
  provider_disabled_by_budget:
    'Provider disabled for the rest of the run after a per-call budget stop',
  deduplicated: 'Provider output already existed in the library (content hash hit)',
  fallback_used: 'Primary asset unavailable; resolved fallbackKey',
};

/**
 * Spend accumulated across provider attempts in one resolution. `unknown`
 * wins over `measured`: a run must never report a partial cost as the total
 * (root hard rule 7).
 */
interface SpendAccumulator {
  requests: number;
  usd: number;
  measured: boolean;
  unknown: boolean;
}

function addSpend(
  spend: SpendAccumulator,
  requests: number,
  costUsd: number | null,
): void {
  if (requests <= 0) {
    return;
  }

  spend.requests += requests;

  if (costUsd === null) {
    spend.unknown = true;
    return;
  }

  spend.usd += costUsd;
  spend.measured = true;
}

function spendCostUsd(spend: SpendAccumulator): number | null {
  if (spend.unknown || !spend.measured) {
    return null;
  }

  return Number(spend.usd.toFixed(6));
}

/** Spend reported by a typed provider failure; `null` means "not reported". */
function providerErrorUsage(error: Error): ProviderCallUsage | null {
  if (
    error instanceof ProviderBudgetError ||
    error instanceof InvalidAssetError ||
    error instanceof ProviderUnavailableError
  ) {
    return error.usage ?? null;
  }

  return null;
}

function diagnostic(
  code: AssetDiagnostic['code'],
  assetKey?: string,
  message: string = DEFAULT_DIAGNOSTIC_MESSAGE[code],
): AssetDiagnostic {
  return assetKey === undefined ? { code, message } : { code, message, assetKey };
}

function tagScore(asset: AssetRecord, tags: readonly string[]): number {
  if (tags.length === 0) {
    return 0;
  }

  const known = new Set(asset.tags.map((tag) => tag.toLowerCase()));

  return tags.reduce(
    (score, tag) => score + (known.has(tag.toLowerCase()) ? 1 : 0),
    0,
  );
}

/** Code-unit comparison: deterministic across locales and hosts. */
function compareKeys(left: AssetRecord, right: AssetRecord): number {
  return left.key < right.key ? -1 : left.key > right.key ? 1 : 0;
}

/** Highest tag score, then key ascending: stable across runs and inputs. */
function bestTagMatch(
  assets: readonly AssetRecord[],
  tags: readonly string[],
): AssetRecord | null {
  let best: AssetRecord | null = null;
  let bestScore = 0;

  for (const asset of [...assets].sort(compareKeys)) {
    const score = tagScore(asset, tags);

    if (score > bestScore) {
      best = asset;
      bestScore = score;
    }
  }

  return best;
}

function assertCommercial(asset: AssetRecord): void {
  if (!asset.license.commercialUse) {
    throw new AssetLicenseError(asset.key, asset.license);
  }
}

function assertCommercialLicense(license: AssetLicense, assetKey: string): void {
  if (!license.commercialUse) {
    throw new AssetLicenseError(assetKey, license);
  }
}

/**
 * Deterministic tiered resolver (ADR-0017 D4).
 *
 * `starter → cache → provider → fallback → typed error`. Provider access is
 * opt-in (`allowProvider: false` by default) and is the only step that can
 * leave the repository — a test asserts zero provider calls without the flag.
 */
export class TieredAssetResolver implements AssetResolver {
  private readonly repository: AssetRepository;
  private readonly starter: readonly AssetRecord[];
  private readonly provider: ImageProvider | null;
  private readonly objectKeyFor: (contentHash: string, fileName: string) => string;
  /** Sticky for the resolver's lifetime (= one render run). */
  private providerDisabledByBudget = false;

  constructor(options: TieredAssetResolverOptions) {
    this.repository = options.repository;
    this.starter = options.starter ?? [];
    this.provider = options.provider ?? null;
    this.objectKeyFor = options.objectKeyFor ?? buildAssetObjectKey;
  }

  async resolve(raw: AssetRequestInput): Promise<AssetResolution> {
    const request = parseAssetRequest(raw);
    const usage: AssetUsage = {
      provider: this.provider?.id ?? null,
      providerRequests: 0,
      cacheHits: 0,
      costUsd: null,
    };
    const spend: SpendAccumulator = {
      requests: 0,
      usd: 0,
      measured: false,
      unknown: false,
    };
    const usageSnapshot = (): AssetUsage => ({
      ...usage,
      providerRequests: spend.requests,
      costUsd: spendCostUsd(spend),
    });
    const diagnostics: AssetDiagnostic[] = [];
    let providerFailure: UnsupportedAssetKindError | null = null;
    let lastProviderError: Error | null = null;

    const starterHit = this.findStarter(request);

    if (starterHit !== null) {
      assertCommercial(starterHit);

      return this.resolved(
        starterHit,
        'starter',
        false,
        [diagnostic('starter_hit', starterHit.key)],
        usageSnapshot(),
      );
    }

    const cached = await this.findCached(request);

    if (cached !== null) {
      assertCommercial(cached);
      usage.cacheHits = 1;

      const code = request.assetKey === undefined ? 'tag_match' : 'cache_hit';

      return this.resolved(
        cached,
        'cache',
        true,
        [diagnostic(code, cached.key)],
        usageSnapshot(),
      );
    }

    if (request.allowProvider) {
      const provider = this.provider;

      if (this.providerDisabledByBudget) {
        diagnostics.push(
          diagnostic('provider_disabled_by_budget', request.assetKey),
        );
      } else if (
        provider !== null &&
        provider.enabled &&
        !provider.supports(request.kind)
      ) {
        // An unsupported kind is a skip, not an abort: the fallback tier still
        // applies (ADR-0017 D4).
        providerFailure = new UnsupportedAssetKindError(request.kind, provider.id);
        diagnostics.push(
          diagnostic(
            'provider_skipped',
            request.assetKey,
            `provider cannot produce kind "${request.kind}"`,
          ),
        );
      } else {
        const generated = await this.generate(
          request,
          spend,
          diagnostics,
          (error) => {
            lastProviderError = error;

            if (error instanceof ProviderBudgetError) {
              this.providerDisabledByBudget = true;
            }
          },
        );

        if (generated !== null) {
          if (generated.cacheHit) {
            usage.cacheHits += 1;
          }

          return this.resolved(
            generated.asset,
            generated.tier,
            generated.cacheHit,
            generated.diagnostics,
            usageSnapshot(),
          );
        }
      }
    } else {
      diagnostics.push(
        diagnostic('provider_skipped', request.assetKey, 'allowProvider is false'),
      );
    }

    if (request.fallbackKey !== undefined) {
      const fallback = await this.findFallback(request);

      if (fallback !== null) {
        assertCommercial(fallback);

        return this.resolved(
          fallback,
          'fallback',
          false,
          [...diagnostics, diagnostic('fallback_used', fallback.key)],
          usageSnapshot(),
        );
      }
    }

    if (providerFailure !== null) {
      throw providerFailure;
    }

    if (lastProviderError !== null) {
      throw lastProviderError;
    }

    if (request.allowProvider) {
      throw new ProviderUnavailableError(
        this.provider?.id ?? null,
        'no provider asset was produced and no fallback resolved',
      );
    }

    throw new UnknownAssetError(
      request.assetKey ?? null,
      request.tags,
      request.styleId,
    );
  }

  private findStarter(request: AssetRequest): AssetRecord | null {
    const candidates = this.starter.filter(
      (asset) => asset.kind === request.kind,
    );

    if (request.assetKey !== undefined) {
      return candidates.find((asset) => asset.key === request.assetKey) ?? null;
    }

    return bestTagMatch(candidates, request.tags);
  }

  private async findCached(request: AssetRequest): Promise<AssetRecord | null> {
    if (request.assetKey !== undefined) {
      const record = await this.repository.findByKey(
        request.assetKey,
        request.styleId,
      );

      if (record !== null) {
        return record.kind === request.kind ? record : null;
      }

      // Alias step (ADR-0017 D3/D11): the bytes already exist under another
      // key, so this key must resolve from the cache instead of the provider.
      const alias = await this.repository.findByAlias(
        request.assetKey,
        request.styleId,
      );

      return alias?.kind === request.kind ? alias : null;
    }

    if (request.tags.length === 0) {
      return null;
    }

    return bestTagMatch(
      (await this.repository.listByStyle(request.styleId)).filter(
        (asset) => asset.kind === request.kind,
      ),
      request.tags,
    );
  }

  private async findFallback(request: AssetRequest): Promise<AssetRecord | null> {
    const key = request.fallbackKey;

    if (key === undefined) {
      return null;
    }

    const record =
      this.starter.find(
        (asset) => asset.key === key && asset.kind === request.kind,
      ) ?? (await this.repository.findByKey(key, request.styleId));

    return record?.kind === request.kind ? record : null;
  }

  private resolved(
    asset: AssetRecord,
    tier: AssetResolution['tier'],
    cacheHit: boolean,
    diagnostics: readonly AssetDiagnostic[],
    usage: AssetUsage,
  ): AssetResolution {
    return {
      asset,
      tier,
      cacheHit,
      diagnostics: [...diagnostics],
      usage: { ...usage },
    };
  }

  private async generate(
    request: AssetRequest,
    spend: SpendAccumulator,
    diagnostics: AssetDiagnostic[],
    onFailure: (error: Error) => void,
  ): Promise<{
    readonly asset: AssetRecord;
    readonly tier: AssetResolution['tier'];
    readonly cacheHit: boolean;
    readonly diagnostics: readonly AssetDiagnostic[];
  } | null> {
    const provider = this.provider;

    if (provider === null || !provider.enabled) {
      diagnostics.push(
        diagnostic(
          'provider_skipped',
          request.assetKey,
          provider === null ? 'no image provider configured' : 'provider is disabled',
        ),
      );

      return null;
    }

    if (!provider.supports(request.kind)) {
      throw new UnsupportedAssetKindError(request.kind, provider.id);
    }

    const key =
      request.assetKey ??
      `generated/${sha256Hex(request.tags.join('|') || 'untagged').slice(0, 12)}`;
    const palette = request.assetPalette ?? assetPaletteFor(request.styleId);

    let result: Awaited<ReturnType<ImageProvider['generate']>>;

    try {
      result = await provider.generate({
        key,
        prompt:
          request.prompt ??
          `Flat 2D vector asset for "${key}". No text, no labels, no letters, no numbers.`,
        kind: request.kind,
        styleId: request.styleId,
        tags: request.tags,
        palette,
      });
    } catch (error) {
      this.providerFailed(error, key, spend, diagnostics, onFailure);

      return null;
    }

    // A completed call is a real attempt even when the bytes are unusable:
    // count it once here and never again on the normalize path below.
    addSpend(spend, 1, result.costUsd);
    assertCommercialLicense(result.asset.license, key);

    if (result.asset.encoding !== 'utf8') {
      this.providerFailed(
        new InvalidAssetError(key, provider.id, 'only utf8 SVG is supported'),
        key,
        spend,
        diagnostics,
        onFailure,
        false,
      );

      return null;
    }

    let normalized: ReturnType<typeof normalizeSvg>;

    try {
      normalized = normalizeSvg(result.asset.data, {
        palette,
      });
    } catch (error) {
      if (error instanceof InvalidSvgError) {
        this.providerFailed(
          new InvalidAssetError(key, provider.id, error.message),
          key,
          spend,
          diagnostics,
          onFailure,
          false,
        );

        return null;
      }

      throw error;
    }

    const contentHash = sha256Hex(normalized.svg);
    const existing = await this.repository.findByContentHash(contentHash);

    if (existing !== null) {
      assertCommercial(existing);

      return {
        asset: existing,
        tier: 'cache',
        cacheHit: true,
        diagnostics: [...diagnostics, diagnostic('deduplicated', existing.key)],
      };
    }

    const source = result.source ?? 'library';
    const objectKey = this.objectKeyFor(contentHash, 'svg');
    const record: AssetRecord = {
      id: buildAssetId(source, key),
      key,
      source,
      kind: 'svg',
      styleId: request.styleId,
      contentHash,
      tags: [...request.tags],
      license: result.asset.license,
      variants: [
        {
          id: 'default',
          objectKey,
          /** Ephemeral data URI so the renderer can consume it without I/O. */
          url: `data:image/svg+xml;base64,${Buffer.from(normalized.svg, 'utf8').toString('base64')}`,
          mimeType: 'image/svg+xml',
          width: result.asset.width,
          height: result.asset.height,
          contentHash,
        },
      ],
      metadata: {
        provider: result.provider,
        model: result.model,
        prompt: request.prompt ?? null,
        removedBackgroundRects: normalized.removedBackgroundRects,
        colorReplacements: normalized.replacements.length,
        maxColorDistance: normalized.maxColorDistance,
      },
    };
    const saved = await this.repository.save(record);
    // A repository returns stored data only (no ephemeral data URI). Keep the
    // just-generated record when it owns these bytes so persistence can upload
    // them without a second provider call; a byte owner under another key wins.
    const resolvedRecord = saved.contentHash === record.contentHash ? record : saved;

    return {
      asset: resolvedRecord,
      tier: 'provider',
      cacheHit: false,
      diagnostics: [
        ...diagnostics,
        diagnostic('provider_generated', resolvedRecord.key),
      ],
    };
  }

  /**
   * Turn a provider failure into a diagnostic plus real spend, and let the
   * caller continue to the fallback tier. The spend is merged only when the
   * error carries usage: a completed-but-unusable call already merged it.
   */
  private providerFailed(
    error: unknown,
    assetKey: string,
    spend: SpendAccumulator,
    diagnostics: AssetDiagnostic[],
    onFailure: (error: Error) => void,
    mergeSpend = true,
  ): void {
    const normalized = error instanceof Error ? error : new Error(String(error));

    if (mergeSpend) {
      const usage = providerErrorUsage(normalized);

      if (usage !== null) {
        addSpend(spend, usage.requests, usage.costUsd);
      } else {
        // The call was attempted but the adapter reported neither tokens nor
        // cost: count the attempt, never invent the price.
        addSpend(spend, 1, null);
      }
    }

    diagnostics.push(
      diagnostic(
        normalized instanceof ProviderBudgetError
          ? 'provider_disabled_by_budget'
          : 'provider_failed',
        assetKey,
        normalized.message.slice(0, 480),
      ),
    );

    onFailure(normalized);
  }
}

